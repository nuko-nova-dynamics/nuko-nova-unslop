import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.resolve(scriptDirectory, "../../..");
const skillDirectory = path.join(repositoryRoot, "skills/nuko-nova-unslop");
const manifestPath = path.join(repositoryRoot, ".codex-plugin/plugin.json");
const outputPath = path.join(repositoryRoot, "apps/mcp/src/skill-package.generated.ts");
const uriRoot = "skill://nuko-nova-unslop/nuko-nova-unslop";

async function collectFiles(directory, relativeDirectory = "") {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    if (entry.name === "__pycache__" || entry.name.endsWith(".pyc")) {
      continue;
    }

    const relativePath = path.posix.join(relativeDirectory, entry.name);
    const absolutePath = path.join(directory, entry.name);

    if (entry.isDirectory()) {
      files.push(...(await collectFiles(absolutePath, relativePath)));
    } else if (entry.isFile()) {
      const content = await readFile(absolutePath, "utf8");
      const digest = createHash("sha256").update(content, "utf8").digest("hex");
      files.push({
        path: relativePath,
        uri: `${uriRoot}/${relativePath}`,
        digest: `sha256:${digest}`,
        content,
      });
    }
  }

  return files;
}

function readCommitSha() {
  if (process.env.GITHUB_SHA) {
    return process.env.GITHUB_SHA;
  }

  try {
    return execFileSync("git", ["rev-parse", "HEAD"], {
      cwd: repositoryRoot,
      encoding: "utf8",
    }).trim();
  } catch {
    return "unknown";
  }
}

const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
const resources = await collectFiles(skillDirectory);
const generated = `// Generated by scripts/generate-skill-package.mjs. Do not edit.\n` +
  `export const GENERATED_SKILL_PACKAGE = ${JSON.stringify({
    name: manifest.name,
    version: manifest.version,
    commitSha: readCommitSha(),
    uriRoot,
    resources,
  }, null, 2)} as const;\n`;

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, generated, "utf8");
